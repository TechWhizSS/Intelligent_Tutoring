    Column(Modifier.fillMaxWidth().background(color,RoundedCornerShape(20.dp)).padding(20.dp),verticalArrangement=Arrangement.spacedBy(13.dp),content=content)
}
@Composable
fun <T>Select(label:String,selected:T,values:List<T>,display:(T)->String={it.toString()},onSelect:(T)->Unit) {
    var expanded by remember {mutableStateOf(false)}
    Column(verticalArrangement=Arrangement.spacedBy(7.dp)) {
        Text(label,style=MaterialTheme.typography.labelMedium,color=Muted)
        Box {
            OutlinedButton(onClick={expanded=true},modifier=Modifier.fillMaxWidth(),shape=RoundedCornerShape(12.dp),contentPadding=PaddingValues(14.dp)) {Text(display(selected),Modifier.weight(1f));Text("⌄")}
            DropdownMenu(expanded,{expanded=false},Modifier.heightIn(max=360.dp)){values.forEach{v->DropdownMenuItem(text={Text(display(v))},onClick={expanded=false;onSelect(v)})}}
        }
    }
}

@Composable
private fun QuizPanel(lesson:Lesson,language:String,store:StudioStore) {
    val questions=lesson.quizzes.getValue(language)
    var answers by remember(lesson.id,language){mutableStateOf(List(questions.size){-1})}
    var checked by remember(lesson.id,language){mutableStateOf(false)}
    Panel(Lavender){Text("Supplemental revision quiz",style=MaterialTheme.typography.titleLarge);Text("Two source-derived questions per topic, not an official examination. Last attempt: ${store.quizResult(lesson.id,language) ?: "Not attempted"}",style=MaterialTheme.typography.bodySmall)}
    questions.forEachIndexed{index,q->Panel(Color.White){Text("${index+1}. ${q.prompt}",fontWeight=FontWeight.SemiBold);q.options.forEachIndexed{option,text->
        Row(verticalAlignment=Alignment.CenterVertically){RadioButton(selected=answers[index]==option,onClick={answers=answers.toMutableList().also{it[index]=option};checked=false});TextButton(onClick={answers=answers.toMutableList().also{it[index]=option};checked=false},modifier=Modifier.weight(1f)){Text(text,color=Ink)}}
    };if(checked)Text("${if(answers[index]==q.correct)"Correct" else "Review this answer"} · ${q.explanation}",style=MaterialTheme.typography.bodySmall,color=Sunrise)}}
    Button(onClick={checked=true;store.quiz(lesson.id,language,answers.indices.count{answers[it]==questions[it].correct},questions.size)},enabled=answers.all{it>=0},modifier=Modifier.fillMaxWidth()){Text("Check my answers")}
}

@Composable
fun AudioExport(file:File,name:String) {
    val context=LocalContext.current
    var message by remember{mutableStateOf("")}
    val scope=rememberCoroutineScope()
    val export=rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("application/octet-stream")){uri->if(uri!=null)scope.launch{message=try{withContext(Dispatchers.IO){context.contentResolver.openOutputStream(uri)?.use{out->file.inputStream().use{it.copyTo(out)}} ?: error("Cannot open destination")};"Audio exported."}catch(_:Exception){"Export failed. Choose another destination."}}}
    val extension=remember(file.absolutePath,file.lastModified()){val h=ByteArray(4);runCatching{file.inputStream().use{it.read(h)}};if(String(h)=="RIFF")"wav" else if(String(h,0,3)=="ID3"||h[0].toInt().and(255)==255)"mp3" else "m4a"}
    OutlinedButton(onClick={export.launch("$name-song.$extension")}){Text("Download / export audio")}
    if(message.isNotBlank())Text(message,style=MaterialTheme.typography.bodySmall)
}

@Composable
private fun ConnectionPanel(ace:AceClient) {
    val context=LocalContext.current
    val scope=rememberCoroutineScope()
    var origin by remember{mutableStateOf(ace.saved()?.origin ?: "")}
    var key by remember{mutableStateOf("")}
    var message by remember{mutableStateOf("")}
    var checking by remember{mutableStateOf(false)}
    fun connect(config:AceConnection){scope.launch{checking=true;try{ace.probe(config);ace.save(config);origin=config.origin;key="";message="GPU API authenticated. Generate a song to test actual vocals and audio."}catch(e:Exception){message=e.message ?: "Connection failed."}finally{checking=false}}}
    val import=rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()){uri->if(uri!=null)scope.launch{try{
        val text=withContext(Dispatchers.IO){context.contentResolver.openInputStream(uri)?.bufferedReader()?.use{reader->val chars=CharArray(8193);var total=0;while(total<chars.size){val n=reader.read(chars,total,chars.size-total);if(n<0)break;total+=n};require(total<=8192){"Connection file is too large."};String(chars,0,total)} ?: error("Cannot open connection file")}
        connect(AceProtocol.fromFile(text))
    }catch(e:Exception){message=e.message ?: "Invalid connection file."}}}
    Panel(Lavender) {
        Text("Music connection",style=MaterialTheme.typography.titleLarge)
        Text("Connect your own running ACE-Step GPU. No paid API or purchased key. Free Colab sessions have availability/time limits; this phone does not host the model.",style=MaterialTheme.typography.bodySmall)
        OutlinedButton(onClick={context.startActivity(Intent(Intent.ACTION_VIEW,Uri.parse("https://colab.research.google.com/github/TechWhizSS/Intelligent_Tutoring/blob/codex/development/notebooks/Free_Singing_GPU.ipynb")))}){Text("Open free GPU notebook ↗")}
        Button(onClick={import.launch(arrayOf("text/*","application/octet-stream"))},enabled=!checking){Text("Import song-service.env")}
        Text("Or enter its HTTPS origin and private connection key. The key is encrypted with Android Keystore. Never paste it into chat.",style=MaterialTheme.typography.bodySmall)
        OutlinedTextField(origin,{origin=it},label={Text("GPU HTTPS origin")},modifier=Modifier.fillMaxWidth(),singleLine=true,enabled=!checking)
        OutlinedTextField(key,{key=it},label={Text("Private GPU connection key")},modifier=Modifier.fillMaxWidth(),singleLine=true,visualTransformation=PasswordVisualTransformation(),enabled=!checking)
        OutlinedButton(onClick={try{connect(AceProtocol.connection(origin,key))}catch(e:Exception){message=e.message.orEmpty()}},enabled=!checking){Text(if(checking)"Checking…" else "Connect and check GPU")}
        OutlinedButton(onClick={ace.disconnect();key="";origin="";message="GPU disconnected."},enabled=!checking){Text("Disconnect GPU")}
        if(message.isNotBlank())Text(message,style=MaterialTheme.typography.bodySmall)
        Text("A connection check proves API authentication only. Singing and educational accuracy require an actual generation and listening review.",style=MaterialTheme.typography.bodySmall,color=Muted)
    }
}

