                }
                ConnectionPanel(ace)
                CompletenessPanel(syllabus,store,history)
                if(student.email=="admin")AdminMaterials(syllabus,lesson,store){choose(it)}
                Text("Sample login and device-local records. Nothing here verifies a college identity. Website and native libraries are separate; cloud sync is not configured.",style=MaterialTheme.typography.bodySmall,color=Muted)
            }
            if(status.isNotBlank())Panel(Lime){Text(status)}
            Text("MBA Tech · CE · First year · Semester I\nLearn the idea. Remember the rhythm.",style=MaterialTheme.typography.bodySmall,color=Muted)
            Spacer(Modifier.height(10.dp))
        }
    }
}

@Composable
private fun LessonSelectors(syllabus:Syllabus,lesson:Lesson,onSelect:(String)->Unit) {
    Select("Subject",lesson.subject,listOf("calculus","beee"),{if(it=="calculus")"Calculus" else "BEEE"}){subject->onSelect(syllabus.topics.first{it.subject==subject}.id)}
    val topics=syllabus.topics.filter{it.subject==lesson.subject}
    Select("Chapter / unit",lesson.unit,topics.map{it.unit}.distinct(),{unit->"Unit $unit · ${topics.first{it.unit==unit}.chapter}"}){unit->onSelect(topics.first{it.unit==unit}.id)}
    val sameUnit=topics.filter{it.unit==lesson.unit}
    Select("Topic / subtopic",lesson.id,sameUnit.map{it.id},{id->sameUnit.first{it.id==id}.title}){onSelect(it)}
}

@Composable
